// Regenerates pkg/glue.mjs from a deployed bundle chunk.
//
//   node tools/new-dha-probe/extract-glue.mjs <chunk.js> <out/glue.mjs>
//
// The wasm-bindgen glue in a Vite/rollup bundle is one contiguous block: the
// externref helpers, the memory views, the closure shims and finally the
// `ap()` import object. Slice the whole block instead of picking functions by
// name: several shims close over private helpers (Ko, Es, ci, lr, hp) and a
// whitelist silently drops them, which only shows up at runtime as
// "Can't find variable: from_slice".
import fs from "node:fs"
import path from "node:path"

const [bundlePath, outPath] = process.argv.slice(2)
if (!bundlePath || !outPath) {
  console.error("usage: node tools/new-dha-probe/extract-glue.mjs <chunk.js> <glue.mjs>")
  process.exit(1)
}
const src = fs.readFileSync(bundlePath, "utf8")

function endOfBlock(s, i) {
  let depth = 0
  let quote = null
  for (; i < s.length; i++) {
    const c = s[i]
    if (quote) {
      if (c === "\\") { i++; continue }
      if (c === quote) quote = null
      continue
    }
    if (c === '"' || c === "'" || c === "`") { quote = c; continue }
    if (c === "/" && s[i + 1] === "/") { const nl = s.indexOf("\n", i); i = nl < 0 ? s.length : nl; continue }
    if (c === "/" && s[i + 1] === "*") { const e = s.indexOf("*/", i + 2); i = e < 0 ? s.length : e + 1; continue }
    if (c === "{" || c === "[" || c === "(") depth++
    else if (c === "}" || c === "]" || c === ")") {
      depth--
      if (depth === 0) return i + 1
    }
  }
  throw new Error("unbalanced block from " + i)
}

function endOfFn(name) {
  const at = src.indexOf(name)
  if (at < 0) throw new Error("not found: " + name)
  let i = at + name.length
  while (i < src.length && src[i] !== "{") i++
  return endOfBlock(src, i)
}

const GLUE_FNS = [
  "function ap(",
  "function op(",
  "function lp(",
  "function cp(",
  "function vs(",
  "function nt(",
  "function tn(",
  "function Ko(",
  "function rt(",
  "function en(",
  "function _s(",
  "function fp(",
  "function mn(",
  "function up(",
  "function dp(",
  "function mp(",
  "async function gp("
]

const starts = GLUE_FNS.map((n) => src.indexOf(n)).filter((n) => n >= 0)
if (!starts.length) throw new Error("glue helpers not found in bundle")
const start = Math.min(...starts)
// the block runs from the import object to the last helper; variable
// declarations (Ho, Es, ci, Vt, ys, kn) sit between them and come along
const end = Math.max(...GLUE_FNS.map((n) => (src.indexOf(n) >= 0 ? endOfFn(n) : 0)))
const region = src.slice(start, end)
if (!region.includes("__wbg_fetch_9ea633a8592ee39a")) throw new Error("import object not in region")
if (region.length > 40_000) throw new Error("region too large, likely caught app code")

const out = `// generated by tools/new-dha-probe/extract-glue.mjs - do not edit by hand
// source: ${path.basename(bundlePath)}
${region}

export const imports = ap()

export function initModule(module) {
  mp(new WebAssembly.Instance(module, imports))
  return be
}

function passString(s) {
  const ptr = mn(s, be.__wbindgen_malloc, be.__wbindgen_realloc)
  return [ptr, Vt]
}

export function get_m3u8_content(link) {
  const [p, n] = passString(link)
  return be.get_m3u8_content(p, n)
}

export function decrypt_segment(url) {
  const [p, n] = passString(url)
  return be.decrypt_segment(p, n)
}
`
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, out)
const missing = ["Ko", "Es", "ci", "mn", "fp", "Vt", "be", "ap"].filter(
  (n) => !new RegExp(`(function|const|let|var) ${n}[= (]`).test(out)
)
console.log("wrote", outPath, out.length, "bytes", missing.length ? "MISSING:" + missing : "all helpers present")
