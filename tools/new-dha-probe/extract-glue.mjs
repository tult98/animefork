// Regenerates pkg/glue.mjs from a deployed bundle chunk.
//
//   node tools/new-dha-probe/extract-glue.mjs <chunk.js> <out/glue.mjs>
//
// The deployed web app inlines the wasm-bindgen shim; this pulls the import
// object and its helpers back out so the same wasm can be driven by a plain
// ES module (Node or the browser) instead of a bundler.
import fs from "node:fs"
import path from "node:path"

const [bundlePath, outPath] = process.argv.slice(2)
if (!bundlePath || !outPath) {
  console.error("usage: node tools/new-dha-probe/extract-glue.mjs <chunk.js> <glue.mjs>")
  process.exit(1)
}
const src = fs.readFileSync(bundlePath, "utf8")

function skipBalanced(s, i) {
  let depth = 0
  let quote = null
  for (; i < s.length; i++) {
    const c = s[i]
    if (quote) {
      if (c === "\\") { i++; continue }
      if (c === quote) quote = null
      continue
    }
    if (c === '"' || c === "'" || c === "`") { quote = c; continue }
    if (c === "/" && s[i + 1] === "/") { const nl = s.indexOf("\n", i); i = nl < 0 ? s.length : nl; continue }
    if (c === "/" && s[i + 1] === "*") { const e = s.indexOf("*/", i + 2); i = e < 0 ? s.length : e + 1; continue }
    if (c === "{" || c === "[" || c === "(") depth++
    else if (c === "}" || c === "]" || c === ")") {
      depth--
      if (depth === 0) return i + 1
    }
  }
  throw new Error("unbalanced block starting at " + i)
}

function grabFn(pattern) {
  const at = src.indexOf(pattern)
  if (at < 0) throw new Error("not found: " + pattern)
  let i = at + pattern.length
  while (i < src.length && src[i] !== "{") {
    if (src[i] === ";" || src[i] === "}") throw new Error("no body for " + pattern)
    i++
  }
  return src.slice(at, skipBalanced(src, i))
}

const parts = {
  vars: "let Vt=0,be;",
  ys: "let ys=null;",
  kn: "let kn=null;",
  ci: 'let ci=new TextDecoder("utf-8",{ignoreBOM:!0,fatal:!0});const hp=2146435072;let lr=0;',
  ho: (() => {
    const at = src.indexOf("const Ho=")
    if (at < 0) throw new Error("not found: const Ho=")
    const end = src.indexOf(";", src.indexOf("FinalizationRegistry(", at))
    return src.slice(at, end + 1)
  })(),
  es: "const Es=new TextEncoder;",
  nt: grabFn("function nt("),
  tn: grabFn("function tn("),
  up: grabFn("function up("),
  vs: grabFn("function vs("),
  en: grabFn("function en("),
  _s: grabFn("function _s("),
  rt: grabFn("function rt("),
  mn: grabFn("function mn("),
  fp: grabFn("function fp("),
  op: grabFn("function op("),
  lp: grabFn("function lp("),
  cp: grabFn("function cp("),
  dp: grabFn("function dp("),
  mp: grabFn("function mp("),
  imports: grabFn("function ap(")
}

const out = `// generated by tools/new-dha-probe/extract-glue.mjs - do not edit by hand
// source: ${path.basename(bundlePath)}
${parts.vars}
${parts.ys}
${parts.kn}
${parts.ci}
${parts.ho}
${parts.es}
${parts.nt}
${parts.tn}
${parts.up}
${parts.vs}
${parts.en}
${parts._s}
${parts.rt}
${parts.mn}
${parts.fp}
${parts.op}
${parts.lp}
${parts.cp}
${parts.dp}
${parts.mp}

${parts.imports}

export const imports = ap()

export function initModule(module) {
  mp(new WebAssembly.Instance(module, imports))
  return be
}

function passString(s) {
  const ptr = mn(s, be.__wbindgen_malloc, be.__wbindgen_realloc)
  return [ptr, Vt]
}

export function get_m3u8_content(link) {
  const [p, n] = passString(link)
  return be.get_m3u8_content(p, n)
}

export function decrypt_segment(url) {
  const [p, n] = passString(url)
  return be.decrypt_segment(p, n)
}
`
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, out)
console.log("wrote", outPath, out.length, "bytes")
